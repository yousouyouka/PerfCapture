const LANG_LIST = ['zh-CN', 'en-US', 'ja-JP'];
let LANG = 'zh-CN';

/** 取词：缺键依次回退 当前语言 → 中文 → fallback → key */
function t(key, fallback) {
  const cur = I18N[LANG];
  if (cur && cur[key] != null) return cur[key];
  const zh = I18N['zh-CN'];
  if (zh && zh[key] != null) return zh[key];
  return fallback != null ? fallback : key;
}

/** 把所有 [data-i18n] 节点替换为当前语言 */
function applyTranslations(root) {
  const scope = root || document;
  scope.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.dataset.i18n;
    const val = t(key, null);
    if (val != null) el.textContent = val;
  });
  scope.querySelectorAll('[data-i18n-title]').forEach((el) => {
    const val = t(el.dataset.i18nTitle, null);
    if (val != null) el.title = val;
  });
  // 更新公告 / 问卷 / 检查更新都有 JS 生成的文案，语言切换后要按新词典重画
  if (typeof window.__refreshUpdates === 'function') window.__refreshUpdates();
  if (typeof window.__refreshSurvey === 'function') window.__refreshSurvey();
  if (typeof window.__refreshExtensions === 'function') window.__refreshExtensions();
  if (typeof window.__refreshRealtime === 'function') window.__refreshRealtime();
  if (window.PerfUpdate && typeof window.PerfUpdate.refresh === 'function') window.PerfUpdate.refresh();
}

function setLanguage(lang) {
  LANG = I18N[lang] ? lang : 'zh-CN';
  document.documentElement.lang = LANG;
  applyTranslations();
  document.querySelectorAll('#segLang button').forEach((b) => {
    b.classList.toggle('is-active', b.dataset.lang === LANG);
  });
  if (typeof state !== 'undefined' && state.report) renderReport(state.report);
}

/** 把模板里的 {name} 用参数替换 */
function fillParams(tpl, params) {
  if (!params) return tpl;
  return String(tpl).replace(/\{(\w+)\}/g, (m, k) => (params[k] != null ? params[k] : m));
}

/**
 * 解析引擎给的 key。
 * 兼容旧报告：旧版 verdicts/features 直接是中文原文，查不到词典就原样返回。
 */
function trKey(key, params) {
  if (key == null) return '';
  if (typeof key !== 'string') return String(key);
  const cur = I18N[LANG] || I18N['zh-CN'];
  const tpl = (cur && cur[key]) || (I18N['zh-CN'] && I18N['zh-CN'][key]);
  if (tpl == null) return key;
  return fillParams(tpl, params);
}

/** verdicts 元素形态：[等级, key, 参数?] 或旧版 [等级, 中文] */
function verdictText(v) {
  if (!v) return '';
  return trKey(v[1], v[2]);
}
